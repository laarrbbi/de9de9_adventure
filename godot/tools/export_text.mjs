// Exports every word the player reads from the web version (www/js/text.js)
// to godot/scripts/words_en.gd, so both versions share one set of words.
// Words only the Godot game uses are in scripts/words_more.gd. Run it again after
// changing the words:
//
//   node godot/tools/export_text.mjs
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { WORDS, SAYINGS } from '../../www/js/text.js';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const entries = (obj) => Object.entries(obj).map(([k, v]) => `\t${JSON.stringify(k)}: ${JSON.stringify(v)},`).join('\n');
writeFileSync(join(ROOT, 'scripts', 'words_en.gd'), `# Generated by tools/export_text.mjs from the web version's www/js/text.js.
# Do not edit by hand; change the words there and run the tool again.
class_name WordsEn

const WORDS := {
${entries(WORDS)}
}

const SAYINGS := {
${entries(SAYINGS)}
}
`);
console.log(`Wrote ${Object.keys(WORDS).length} words to scripts/words_en.gd`);
